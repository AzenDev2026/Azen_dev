_current_lang = "en_US"


def set_language(lang: str):
    global _current_lang
    if lang in STRINGS:
        _current_lang = lang


def get_language() -> str:
    return _current_lang


def detect_system_language() -> str:
    """按 LANG/LC_ALL 环境变量猜测语言，返回我们支持的语言代码。"""
    import os
    raw = os.environ.get("LC_ALL") or os.environ.get("LC_MESSAGES") or os.environ.get("LANG", "")
    raw = raw.lower()
    if not raw:
        return "en_US"
    # 匹配我们支持的五个
    for code in ("zh", "ja", "fr", "de"):
        if raw.startswith(code):
            return {
                "zh": "zh_CN",
                "ja": "ja_JP",
                "fr": "fr_FR",
                "de": "de_DE",
            }[code]
    return "en_US"


def t(key: str, **kwargs) -> str:
    """取翻译字符串，支持 {name} 占位。"""
    table = STRINGS.get(_current_lang, STRINGS["en_US"])
    text = table.get(key) or STRINGS["en_US"].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text